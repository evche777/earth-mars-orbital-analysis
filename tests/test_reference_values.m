function tests = test_reference_values
tests = functiontests(localfunctions);
end

function setupOnce(testCase)
projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(projectRoot, 'src'));
testCase.TestData.results = earth_mars_transfer_analysis(tempdir, false);
end

function testTransferTime(testCase)
verifyEqual(testCase, ...
    testCase.TestData.results.transferTimeDays, ...
    258.8657589, 'AbsTol', 1e-4);
end

function testPhaseAngle(testCase)
verifyEqual(testCase, ...
    testCase.TestData.results.phaseAngleDegrees, ...
    44.3441711, 'AbsTol', 1e-4);
end

function testHyperbolicExcessSpeeds(testCase)
verifyEqual(testCase, ...
    testCase.TestData.results.earthDepartureVInfinity_km_s, ...
    2.9446893, 'AbsTol', 1e-5);
verifyEqual(testCase, ...
    testCase.TestData.results.marsArrivalVInfinity_km_s, ...
    2.6488952, 'AbsTol', 1e-5);
end

function testDeltaVBudget(testCase)
verifyEqual(testCase, ...
    testCase.TestData.results.departureDeltaV_km_s, ...
    3.5899784, 'AbsTol', 1e-5);
verifyEqual(testCase, ...
    testCase.TestData.results.captureDeltaV_km_s, ...
    2.0906392, 'AbsTol', 1e-5);
verifyEqual(testCase, ...
    testCase.TestData.results.totalDeltaV_km_s, ...
    5.6806175, 'AbsTol', 1e-5);
end

function testNumericalArrival(testCase)
verifyLessThan(testCase, ...
    testCase.TestData.results.arrivalMissDistance_km, 10.0);
end

